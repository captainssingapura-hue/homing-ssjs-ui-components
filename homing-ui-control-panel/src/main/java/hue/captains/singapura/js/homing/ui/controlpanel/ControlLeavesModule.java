/**
 * What each leaf of the house is controlled by, as a page has it, generated from {@link HouseControllability} beside the
 * catalogue of options ({@link ControlCatalogueModule}) - a map per leaf, written as the groups of leaves that share
 * an answer, so what is served grows with the kinds of answer, not with the leaves the house has:
 *
 * <ul>
 *   <li>{@code CONTROL_TYPE_OF[leaf]} - every leaf of the house's taxonomy, by its token, and its
 *       control type, found up its lineage;</li>
 *   <li>{@code CONTROL_OPTIONS_OF[leaf]} - every leaf, and what it is controlled by: a degree for
 *       each axis it varies along, then its type's options.</li>
 * </ul>
 */
public record ControlLeavesModule() implements EsModule<ControlLeavesModule>, SelfContent {

    public static final ControlLeavesModule INSTANCE = new ControlLeavesModule();

    public record CONTROL_TYPE_OF() implements Exportable._Constant<ControlLeavesModule> {}
    public record CONTROL_OPTIONS_OF() implements Exportable._Constant<ControlLeavesModule> {}

    @Override public ImportsFor<ControlLeavesModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<ControlLeavesModule> exports() {
        return new ExportsOf<>(INSTANCE, List.of(new CONTROL_TYPE_OF(), new CONTROL_OPTIONS_OF()));
    }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        var house = HouseControllability.INSTANCE;
        Taxonomy taxonomy = InstalledStyling.get().taxonomy();
        List<Component<?>> leaves = taxonomy.components().stream().filter(c -> !(c instanceof VirtualComponent<?>)).toList();   // a design draws a virtual leaf; nothing controls it
        var byType = new LinkedHashMap<String, List<String>>();          // a control type → the leaves of it, in the taxonomy's order
        var byOptions = new LinkedHashMap<List<String>, List<String>>(); // what leaves are controlled by → those leaves
        for (Component<?> c : leaves) {
            byType.computeIfAbsent(house.findControlType(taxonomy, c).name(), k -> new ArrayList<>()).add(c.token());
            byOptions.computeIfAbsent(house.optionsFor(taxonomy, c).stream().map(o -> o.name().value()).toList(), k -> new ArrayList<>()).add(c.token());
        }
        String typeOf = byType.entrySet().stream()
                .map(e -> "[" + quoted(e.getKey()) + ", " + listed(e.getValue()) + "]")
                .collect(Collectors.joining(",\n    "));
        String optionsOf = byOptions.entrySet().stream()
                .map(e -> "[Object.freeze(" + listed(e.getKey()) + "), " + listed(e.getValue()) + "]")
                .collect(Collectors.joining(",\n    "));
        return List.of(
                "// Generated by ControlLeavesModule from HouseControllability - do not hand-edit.",
                "// Every leaf of the house's taxonomy, and its control type: written as each type and the leaves of it.",
                "const CONTROL_TYPE_OF = Object.freeze(Object.fromEntries([\n    " + typeOf + "\n].flatMap(([type, leaves]) => leaves.map((leaf) => [leaf, type]))));",
                "// Every leaf of the house's taxonomy, and what it is controlled by - its axes' degrees, then its type's options:",
                "// written as each list and the leaves it controls.",
                "const CONTROL_OPTIONS_OF = Object.freeze(Object.fromEntries([\n    " + optionsOf + "\n].flatMap(([options, leaves]) => leaves.map((leaf) => [leaf, options]))));");
    }

    private static String listed(List<String> tokens) { return "[" + tokens.stream().map(ControlLeavesModule::quoted).collect(Collectors.joining(", ")) + "]"; }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }
}
