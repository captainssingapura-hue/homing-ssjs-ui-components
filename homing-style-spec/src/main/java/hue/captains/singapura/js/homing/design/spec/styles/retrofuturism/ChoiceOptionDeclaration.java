/** retro-futurism's declaration of choice-option: its own implementation, and a spec for each of its slots. */
public record ChoiceOptionDeclaration() implements CastingDeclaration<BaseScheme, RetroFuturism, HouseItems.ChoiceOption, RoleRoot> {
    @Override public CastingImplementation<BaseScheme, RetroFuturism, HouseItems.ChoiceOption, RoleRoot> own() { return new ChoiceOption(); }

    @Override public PartsSpec<BaseScheme, RetroFuturism, HouseItems.ChoiceOption> parts() {
        return new PartsSpec<>(List.of(
                new PartSpec.SameRole<>(HouseItems.ChoiceOption.INSTANCE, HouseText.Caption.INSTANCE, HouseSaying.Note.INSTANCE, new Target.Impl<>(new CaptionNote()))));
    }
}
