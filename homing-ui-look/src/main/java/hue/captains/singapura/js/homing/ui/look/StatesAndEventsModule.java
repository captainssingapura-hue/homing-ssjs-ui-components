package hue.captains.singapura.js.homing.ui.look;

import hue.captains.singapura.js.homing.component.taxonomy.Classed;
import hue.captains.singapura.js.homing.component.taxonomy.StateType;
import hue.captains.singapura.js.homing.component.taxonomy.StateValue;
import hue.captains.singapura.js.homing.component.taxonomy.Taxonomy;
import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.design.styling.InstalledStyling;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * The old look's table of the house's classed states, as a page has it, generated from the taxonomy as read on this
 * classpath - {@code STATE[NAME]}: {@code { token, values, rest, words, changed }} - its values, which exclude one
 * another, the one at rest first; the design word each value but the rest is answered by ({@code
 * ENABLED.words["false"]} is {@code disabled}); {@code changed} the old type of its change. Its table of events is
 * gone with the tree of events (RFC 0069, amended): what is not yet ported names it still, and does not load. It
 * retires with the old look.
 */
public record StatesAndEventsModule() implements EsModule<StatesAndEventsModule>, SelfContent {

    public static final StatesAndEventsModule INSTANCE = new StatesAndEventsModule();

    public record STATE() implements Exportable._Constant<StatesAndEventsModule> {}

    @Override public ImportsFor<StatesAndEventsModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<StatesAndEventsModule> exports() {
        return new ExportsOf<>(INSTANCE, List.of(new STATE()));
    }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        Taxonomy house = InstalledStyling.get().taxonomy();
        var states = new ArrayList<String>();
        for (StateType<?> t : house.states().types()) {
            if (!(t instanceof Classed<?> s)) continue;   // the old look draws classes: its classed states alone
            String token = s.name().value();
            List<StateValue> values = s.values();
            states.add(constant(token) + ": Object.freeze({ token: " + quoted(token)
                    + ", values: Object.freeze([" + String.join(", ", values.stream().map(v -> quoted(v.token())).toList()) + "])"
                    + ", rest: " + quoted(values.get(0).token())
                    + ", words: Object.freeze({ " + String.join(", ", values.subList(1, values.size()).stream()
                            .map(v -> quoted(v.token()) + ": " + quoted(s.word(v))).toList()) + " })"
                    + ", changed: " + type(token + "-changed")
                    + ", toString() { return " + quoted(token) + "; } })");
        }
        return List.of(
                "// Generated by StatesAndEventsModule from the house's tree of states - do not hand-edit.",
                "// Every classed type of state, and the old type of its change.",
                "const STATE = Object.freeze({\n    " + String.join(",\n    ", states) + "\n});");
    }

    /** {@code Object.freeze({ token: "click", toString() { return "click"; } })} */
    private static String type(String token) {
        return "Object.freeze({ token: " + quoted(token) + ", toString() { return " + quoted(token) + "; } })";
    }

    /** {@code enabled} gives {@code ENABLED}. */
    private static String constant(String token) { return token.toUpperCase(Locale.ROOT).replace('-', '_'); }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }
}
