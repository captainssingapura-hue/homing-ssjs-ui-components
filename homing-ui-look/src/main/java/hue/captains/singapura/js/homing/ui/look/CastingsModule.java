package hue.captains.singapura.js.homing.ui.look;

import hue.captains.singapura.js.homing.component.taxonomy.Component;
import hue.captains.singapura.js.homing.component.taxonomy.Part;
import hue.captains.singapura.js.homing.component.taxonomy.Role;
import hue.captains.singapura.js.homing.component.taxonomy.RoleBranch;
import hue.captains.singapura.js.homing.component.taxonomy.RoleNode;
import hue.captains.singapura.js.homing.component.taxonomy.Taxonomy;
import hue.captains.singapura.js.homing.component.taxonomy.VirtualComponent;
import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.ui.taxonomy.HouseShaping;
import hue.captains.singapura.js.homing.ui.taxonomy.HouseTaxonomy;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * The house's roles and castings as a page has them, generated from its taxonomy - so no second
 * list can drift from it (RFC 0067, appendix Castings):
 *
 * <ul>
 *   <li>{@code ROLE[NAME]} - Standalone, a component on its own, then every role of the
 *       catalogue: {@code { token, functional }}, functional for a role of the Shaping branch,
 *       whose part is cast for its look as Standalone;</li>
 *   <li>{@code CASTINGS[leaf]} - every leaf but a virtual one, by its token, and the roles it may be cast in:
 *       Standalone, then each role a declared slot casts it in.</li>
 * </ul>
 *
 * <p>Every leaf may stand alone until the taxonomy declares the part-only ones.</p>
 */
public record CastingsModule() implements EsModule<CastingsModule>, SelfContent {

    public static final CastingsModule INSTANCE = new CastingsModule();

    public record ROLE() implements Exportable._Constant<CastingsModule> {}

    public record CASTINGS() implements Exportable._Constant<CastingsModule> {}

    @Override public ImportsFor<CastingsModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<CastingsModule> exports() {
        return new ExportsOf<>(INSTANCE, List.of(new ROLE(), new CASTINGS()));
    }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        Taxonomy taxonomy = HouseTaxonomy.INSTANCE.read();
        Set<RoleNode> functional = under(taxonomy, HouseShaping.Shaping.INSTANCE);
        var roles = new ArrayList<String>();
        roles.add(role("standalone", false));
        for (Role<?> r : taxonomy.roles()) roles.add(role(r.name().value(), functional.contains(r)));
        String castings = taxonomy.components().stream()
                .filter(c -> !(c instanceof VirtualComponent<?>))   // never cast: a design's concrete leaf is worn
                .map((Component<?> c) -> quoted(c.token()) + ": Object.freeze([" + String.join(", ", castOf(taxonomy, c)) + "])")
                .collect(Collectors.joining(",\n    "));
        return List.of(
                "// Generated by CastingsModule from the house's taxonomy - do not hand-edit.",
                "// Standalone, then every role of the catalogue: functional for a role that only places its part.",
                "const ROLE = Object.freeze({\n    " + String.join(",\n    ", roles) + "\n});",
                "// Every leaf, and the roles it may be cast in: Standalone, then each role a declared slot casts it in.",
                "const CASTINGS = Object.freeze({\n    " + castings + "\n});");
    }

    /** {@code GO: Object.freeze({ token: "go", functional: false, toString() { return "go"; } })} */
    private static String role(String token, boolean functional) {
        return token.toUpperCase(Locale.ROOT).replace('-', '_') + ": Object.freeze({ token: " + quoted(token)
                + ", functional: " + functional + ", toString() { return " + quoted(token) + "; } })";
    }

    /** Standalone, then the roles of every slot the component plays, each once, in the slots' order. */
    private static List<String> castOf(Taxonomy taxonomy, Component<?> c) {
        var out = new LinkedHashSet<String>();
        out.add(quoted("standalone"));
        for (Part<?, ?> p : taxonomy.parts()) if (p.base().equals(c)) out.add(quoted(p.role().name().value()));
        return List.copyOf(out);
    }

    /** Every role node under a branch of the catalogue. */
    private static Set<RoleNode> under(Taxonomy taxonomy, RoleBranch branch) {
        var out = new HashSet<RoleNode>();
        for (RoleNode n : taxonomy.children(branch)) {
            out.add(n);
            if (n instanceof RoleBranch b) out.addAll(under(taxonomy, b));
        }
        return out;
    }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }
}
