package hue.captains.singapura.js.homing.ui.look;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.design.styling.LeafClasses;
import hue.captains.singapura.js.homing.ui.taxonomy.HouseTaxonomy;

import java.util.List;

/**
 * What a page knows of the house's leaves, generated from the taxonomy so it cannot drift from it (RFC 0067, appendix
 * Two Classes per Leaf): {@code LEAVES[token]} - every leaf, its own and every extension's on the classpath, with its
 * style-aware class and each application state it lists with every value's class - what {@code Look} wears through
 * core's {@code StyledLeaf}.
 */
public record LookManifestModule() implements EsModule<LookManifestModule>, SelfContent {

    public static final LookManifestModule INSTANCE = new LookManifestModule();

    public record LEAVES() implements Exportable._Constant<LookManifestModule> {}

    @Override public ImportsFor<LookManifestModule> imports() { return ImportsFor.noImports(); }

    @Override public ExportsOf<LookManifestModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new LEAVES())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of(
                "// Generated by LookManifestModule from the house's taxonomy - do not hand-edit.",
                "// Every leaf, its style-aware class and its application states' classes, as StyledLeaf wears them.",
                "const LEAVES = " + LeafClasses.INSTANCE.script(HouseTaxonomy.INSTANCE.read()) + ";");
    }
}
