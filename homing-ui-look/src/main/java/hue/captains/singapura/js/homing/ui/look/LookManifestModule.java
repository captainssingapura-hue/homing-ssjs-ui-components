package hue.captains.singapura.js.homing.ui.look;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * What a page knows of the house's looks, generated with the sheet so it cannot drift from it:
 *
 * <ul>
 *   <li>{@code LOOK_TARGETS} - every CSS target, in the tree's order: a component wears its
 *       casting's look on each;</li>
 *   <li>{@code TREATED[component]} - the treatments the sheet has a rule for, by component:
 *       {@code effect-opacity--disabled} - a component wears each, and its rule shows while its
 *       state's reflection is written.</li>
 * </ul>
 */
public record LookManifestModule() implements EsModule<LookManifestModule>, SelfContent {

    public static final LookManifestModule INSTANCE = new LookManifestModule();

    public record LOOK_TARGETS() implements Exportable._Constant<LookManifestModule> {}

    public record TREATED() implements Exportable._Constant<LookManifestModule> {}

    @Override public ImportsFor<LookManifestModule> imports() { return ImportsFor.noImports(); }

    @Override public ExportsOf<LookManifestModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new LOOK_TARGETS(), new TREATED())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        String targets = HouseLooks.targets().stream().map(LookManifestModule::quoted).collect(Collectors.joining(", "));
        Map<String, List<String>> treated = HouseLooks.treated();
        String byComponent = treated.entrySet().stream()
                .map(e -> quoted(e.getKey()) + ": Object.freeze([" + e.getValue().stream().map(LookManifestModule::quoted).collect(Collectors.joining(", ")) + "])")
                .collect(Collectors.joining(",\n    "));
        return List.of(
                "// Generated by LookManifestModule from the house's flattened sheet - do not hand-edit.",
                "// Every CSS target, in the tree's order: a component wears its casting's look on each.",
                "const LOOK_TARGETS = Object.freeze([" + targets + "]);",
                "// The treatments the sheet has a rule for, by component: worn always, shown while the state's reflection is written.",
                "const TREATED = Object.freeze({\n    " + byComponent + "\n});");
    }

    private static String quoted(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }
}
