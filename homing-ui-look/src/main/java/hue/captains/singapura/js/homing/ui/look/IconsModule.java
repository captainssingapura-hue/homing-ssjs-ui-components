import java.util.List;
import java.util.Locale;

/**
 * The icons a page may show (RFC 0067, D52), generated from the installed instance's taxonomy: {@code ICON}, one frozen
 * constant for each leaf of the Icon branch - the house's and every downstream's the instance registers -
 * {@code ICON.CLOSE_ICON}, which is the icon's leaf as a component wears it ({@code LEAF}, its token). The {@code Icon}
 * component is handed one, and an owner that takes an icon from its caller is handed one, never a name; a menu's rows,
 * which come as data, name an icon by its token, looked up here. The picture is the icon's look, the style worn's.
 */
public record IconsModule() implements EsModule<IconsModule>, SelfContent {

    public static final IconsModule INSTANCE = new IconsModule();

    /** Each icon: {@code ICON.CLOSE_ICON = { LEAF: "close-icon" }}, frozen. */
    public record ICON() implements Exportable._Constant<IconsModule> {}

    @Override public ImportsFor<IconsModule> imports() { return ImportsFor.noImports(); }

    @Override public ExportsOf<IconsModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new ICON())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        var lines = new ArrayList<String>();
        lines.add("// Generated by IconsModule from the installed instance's taxonomy - do not hand-edit.");
        lines.add("// Every icon, a leaf of the Icon branch: what an icon is handed, what an owner that shows one is given.");
        var entries = new ArrayList<String>();
        for (Component<?> c : Icons.INSTANCE.of(InstalledStyling.get().taxonomy())) {
            String token = c.token();
            entries.add("    " + token.toUpperCase(Locale.ROOT).replace('-', '_') + ": Object.freeze({ LEAF: " + StampedParams.jsString(token)
                    + ", toString() { return " + StampedParams.jsString(token) + "; } })");
        }
        lines.add("const ICON = Object.freeze({\n" + String.join(",\n", entries) + "\n});");
        return lines;
    }

    /** The icons of a taxonomy: every component under the Icon branch, in the order read. */
    public record Icons() implements StatelessFunctionalObject {

        public static final Icons INSTANCE = new Icons();

        public List<Component<?>> of(Taxonomy taxonomy) {
            var out = new ArrayList<Component<?>>();
            for (Component<?> c : taxonomy.components())
                for (ComponentBranch b = taxonomy.parent(c); b != null; b = taxonomy.parent(b))
                    if (b.equals(HouseBranches.Icon.INSTANCE)) { out.add(c); break; }
            return List.copyOf(out);
        }
    }
}
